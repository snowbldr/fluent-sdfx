// ExportOptions shape the Go a history exports to.
type ExportOptions struct {
	Package string // default main
	// Main adds a main that writes each body to <name>.stl at CellsPerMM.
	Main       bool
	CellsPerMM float64 // default 4
	Source     string  // the history's file name, for the header comment
}

// ExportGo returns a Go source file that builds the same part with the
// fluent API: params as constants, one statement per step named as in the
// history, anchors as the calls that find them, provenance as a comment
// above its step, and a Build function returning the bodies by name.
// Bakes are a runtime cache and do not appear. The history must evaluate
// without failed or blocked steps; off steps are left out.
func ExportGo(h *History, o ExportOptions) ([]byte, error) {
	if o.Package == "" {
		o.Package = "main"
	}
	if o.CellsPerMM == 0 {
		o.CellsPerMM = 4
	}
	res := NewRuntime(Options{}).Eval(h)
	if err := res.Err(); err != nil {
		return nil, fmt.Errorf("export: %w", err)
	}
	x := &exporter{h: h, res: res, names: map[string]int{}, imports: map[string]string{}, aliases: map[string]string{}, idents: map[string]bool{}, used: map[string]bool{}, helpers: map[string]bool{}}
	for _, p := range []string{"solid"} {
		x.pkg(p)
	}
	for i, s := range h.Steps {
		if s.Name != "" {
			x.names[s.Name] = i
		}
	}
	x.analysis()
	x.declareParams()
	x.vars = make([]string, len(h.Steps))
	for i, s := range h.Steps {
		base := s.Name
		if base == "" {
			base = fmt.Sprintf("step%d", i)
		}
		x.vars[i] = x.ident(base)
	}

	var body strings.Builder
	for i := range h.Steps {
		x.i = i
		code, err := x.step(i)
		if err != nil {
			return nil, fmt.Errorf("export: %s: %w", x.label(i), err)
		}
		body.WriteString(code)
	}

	var hs []string
	for h := range x.helpers {
		if strings.HasPrefix(h, "mirror") && strings.HasSuffix(h, "s") {
			x.helpers[strings.TrimSuffix(h, "s")] = true
		}
	}
	for h := range x.helpers {
		hs = append(hs, h)
	}
	sort.Strings(hs)
	var helpers strings.Builder
	for _, h := range hs {
		helpers.WriteString(x.helperSrc(h))
	}

	var out strings.Builder
	src := ""
	if o.Source != "" {
		src = " from " + o.Source
	}
	fmt.Fprintf(&out, "// Code generated by fluent-sdfx history export%s. Edit the history and\n// export again, or take this file over and stop exporting.\n\n", src)
	fmt.Fprintf(&out, "package %s\n\n", o.Package)
	var paths []string
	for p := range x.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	out.WriteString("import (\n")
	for _, p := range paths {
		if a := x.imports[p]; a != path.Base(p) {
			fmt.Fprintf(&out, "\t%s %q\n", a, p)
		} else {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
	}
	out.WriteString(")\n\n")
	out.WriteString(x.paramDecls)
	out.WriteString("// Build makes the part and returns its bodies by name.\n")
	fmt.Fprintf(&out, "func Build() map[string]*%s.Solid {\n", x.imports[modPath+"/solid"])
	out.WriteString(body.String())
	var unused []string
	for i, v := range x.vars {
		if v != "" && !x.used[v] && !x.isBody(i) && x.declared[i] {
			unused = append(unused, v)
		}
	}
	if len(unused) > 0 {
		fmt.Fprintf(&out, "\t%s = %s\n", strings.TrimSuffix(strings.Repeat("_, ", len(unused)), ", "), strings.Join(unused, ", "))
	}
	fmt.Fprintf(&out, "\treturn map[string]*%s.Solid{\n", x.imports[modPath+"/solid"])
	for _, b := range res.Bodies {
		e := expr{x.vars[b.Step], res.Steps[b.Step].value.Type()}
		e, err := x.fit(e, solidType)
		if err != nil {
			return nil, fmt.Errorf("export: body %s: %w", b.Name, err)
		}
		fmt.Fprintf(&out, "\t\t%q: %s,\n", b.Name, e.code)
	}
	out.WriteString("\t}\n}\n")
	if o.Main {
		fmt.Fprintf(&out, "\nfunc main() {\n\tfor name, s := range Build() {\n\t\ts.STL(name+\".stl\", %s)\n\t}\n}\n", num(o.CellsPerMM))
	}
	out.WriteString(helpers.String())
	b, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("export: the generated Go does not parse (a bug): %w\n%s", err, out.String())
	}
	return b, nil
}

const modPath = "github.com/snowbldr/fluent-sdfx"

type expr struct {
	code string
	t    reflect.Type
}

type exporter struct {
	h          *History
	res        *Result
	names      map[string]int
	infos      []stepInfo
	vars       []string
	declared   []bool
	imports    map[string]string // import path to alias
	aliases    map[string]string // alias to import path
	idents     map[string]bool   // identifiers taken in Build
	params     map[string]expr
	paramDecls string
	used       map[string]bool
	helpers    map[string]bool
	i          int
	input      *expr // the current step's input, for inline anchors
}

func (x *exporter) label(i int) string { return x.res.Steps[i].label() }

func (x *exporter) isBody(i int) bool {
	for _, b := range x.res.Bodies {
		if b.Step == i {
			return true
		}
	}
	return false
}

func (x *exporter) analysis() {
	sc := &scope{h: x.h, names: x.names}
	x.infos = make([]stepInfo, len(x.h.Steps))
	for i := range x.h.Steps {
		x.infos[i] = sc.analyze(i)
	}
	x.declared = make([]bool, len(x.h.Steps))
}

// pkg returns the alias for a package, importing it.
func (x *exporter) pkg(p string) string {
	full := p
	switch p {
	case "solid", "shape", "sculpt", "anchor", "obj", "layout", "plane":
		full = modPath + "/" + p
	case "v3", "v2", "v3i", "v2i", "p2":
		full = modPath + "/vec/" + p
	case "sdf":
		full = "github.com/snowbldr/sdfx/sdf"
	}
	if a, ok := x.imports[full]; ok {
		return a
	}
	a := path.Base(full)
	for n := 2; x.aliases[a] != ""; n++ {
		a = fmt.Sprintf("%s%d", path.Base(full), n)
	}
	x.imports[full], x.aliases[a] = a, full
	return a
}

// ident makes a unique Go identifier for a step or param name.
func (x *exporter) ident(name string) string {
	id := name
	if token.Lookup(id).IsKeyword() || x.aliases[id] != "" || isPredeclared(id) {
		id += "_"
	}
	for n := 2; x.idents[id]; n++ {
		id = fmt.Sprintf("%s%d", name, n)
	}
	x.idents[id] = true
	return id
}

func isPredeclared(id string) bool {
	switch id {
	case "len", "cap", "append", "make", "new", "copy", "delete", "panic", "recover", "print", "println", "min", "max", "clear",
		"true", "false", "nil", "iota", "int", "float64", "string", "bool", "error", "any", "byte", "rune", "must":
		return true
	}
	return false
}

func (x *exporter) declareParams() {
	x.params = map[string]expr{}
	var names []string
	for n := range x.h.Params {
		names = append(names, n)
	}
	sort.Strings(names)
	var consts, vars strings.Builder
	for _, n := range names {
		id := x.ident(n)
		switch v := x.h.Params[n].(type) {
		case []any:
			var parts []string
			for _, c := range v {
				f, ok := toFloat(c)
				if !ok {
					continue
				}
				parts = append(parts, num(f))
			}
			switch len(parts) {
			case 3:
				fmt.Fprintf(&vars, "\t%s = %s.XYZ(%s)\n", id, x.pkg("v3"), strings.Join(parts, ", "))
				x.params[n] = expr{id, vec3Type}
			case 2:
				fmt.Fprintf(&vars, "\t%s = %s.XY(%s)\n", id, x.pkg("v2"), strings.Join(parts, ", "))
				x.params[n] = expr{id, vec2Type}
			}
		case string:
			fmt.Fprintf(&consts, "\t%s = %q\n", id, v)
			x.params[n] = expr{id, stringType}
		case bool:
			fmt.Fprintf(&consts, "\t%s = %v\n", id, v)
			x.params[n] = expr{id, reflect.TypeOf(true)}
		default:
			if f, ok := toFloat(v); ok {
				fmt.Fprintf(&consts, "\t%s = %s\n", id, num(f))
				x.params[n] = expr{id, untypedNum}
			}
		}
	}
	var b strings.Builder
	if consts.Len() > 0 {
		fmt.Fprintf(&b, "// The history's params.\nconst (\n%s)\n\n", consts.String())
	}
	if vars.Len() > 0 {
		fmt.Fprintf(&b, "var (\n%s)\n\n", vars.String())
	}
	x.paramDecls = b.String()
}

var (
	stringType = reflect.TypeOf("")
	untypedNum = reflect.TypeOf(struct{ untypedNumber int }{})
)

// step writes the statements for step i.
func (x *exporter) step(i int) (string, error) {
	s := x.h.Steps[i]
	info := x.infos[i]
	v := x.vars[i]
	var b strings.Builder
	if s.By != "" || s.From != "" {
		var parts []string
		if s.By != "" {
			parts = append(parts, s.By)
		}
		if s.From != "" {
			parts = append(parts, s.From)
		}
		fmt.Fprintf(&b, "\t// %s\n", strings.Join(parts, ", "))
	}
	if s.Off {
		if info.input >= 0 && x.declared[info.input] {
			fmt.Fprintf(&b, "\t%s := %s // off in the history: passes its input\n", v, x.useVar(info.input))
			x.declared[i] = true
			return b.String(), nil
		}
		return "", nil
	}
	x.input = nil
	var in *expr
	if s.Anchor == nil {
		if s.On != "" {
			e, err := x.ref(s.On)
			if err != nil {
				return "", err
			}
			in = &e
		} else if info.input >= 0 {
			e := expr{x.useVar(info.input), x.typeOf(info.input)}
			in = &e
		}
	}
	x.input = in

	if s.Anchor != nil {
		var surf *expr
		if s.Anchor.On == "" && info.input >= 0 {
			surf = &expr{x.useVar(info.input), x.typeOf(info.input)}
		}
		e, err := x.anchor(s.Anchor, surf)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "\t%s := %s\n", v, e.code)
		x.declared[i] = true
		return b.String(), nil
	}

	method := !strings.Contains(s.Op, ".")
	var call expr
	var args []expr
	var fnType reflect.Type
	var err error
	if method {
		recv := *in
		mt, recvExpr, ok := methodOf(recv, s.Op)
		if !ok {
			return "", fmt.Errorf("no method %s on %s", s.Op, typeName(recv.t))
		}
		fnType = mt
		args, err = x.args(x.sigParams(recv.t, s.Op), mt, 1, s.Args)
		if err != nil {
			return "", err
		}
		call = x.callExpr(recvExpr.code+"."+s.Op, mt, args)
	} else {
		c, ok := lookupFunc(s.Op)
		if !ok {
			return "", fmt.Errorf("no op %s", s.Op)
		}
		name, err := x.funcName(c)
		if err != nil {
			return "", err
		}
		fnType = c.fn.Type()
		start := 0
		var first []expr
		if in != nil {
			f, err := x.fit(*in, fnType.In(0))
			if err != nil {
				return "", fmt.Errorf("on: %w", err)
			}
			first, start = []expr{f}, 1
		}
		args, err = x.args(c.params, fnType, start, s.Args)
		if err != nil {
			return "", err
		}
		call = x.callExpr(name, fnType, append(first, args...))
	}
	cur := call
	if s.Mirror != "" {
		// The op's result is the mirrored call's input, so it gets a name.
		first := x.ident(v + "Unmirrored")
		fmt.Fprintf(&b, "\t%s := %s\n", first, call.code)
		cur = expr{first, call.t}
		axis := strings.ToUpper(s.Mirror)
		mirrored := make([]expr, len(args))
		for k, a := range args {
			mirrored[k] = a
			switch a.t {
			case vec3Type:
				x.helpers["mirror"+axis] = true
				mirrored[k] = expr{"mirror" + axis + "(" + a.code + ")", vec3Type}
			case vec3sType:
				x.helpers["mirror"+axis+"s"] = true
				mirrored[k] = expr{"mirror" + axis + "s(" + a.code + ")", vec3sType}
			}
		}
		if method {
			mt, recvExpr, _ := methodOf(cur, s.Op)
			cur = x.callExpr(recvExpr.code+"."+s.Op, mt, mirrored)
		} else {
			c, _ := lookupFunc(s.Op)
			name, _ := x.funcName(c)
			f, err := x.fit(cur, fnType.In(0))
			if err != nil {
				return "", err
			}
			cur = x.callExpr(name, fnType, append([]expr{f}, mirrored...))
		}
	}
	for k, t := range s.Then {
		mt, recvExpr, ok := methodOf(cur, t.Op)
		if !ok {
			return "", fmt.Errorf("then[%d]: no method %s on %s", k, t.Op, typeName(cur.t))
		}
		targs, err := x.args(x.sigParams(cur.t, t.Op), mt, 1, t.Args)
		if err != nil {
			return "", fmt.Errorf("then[%d]: %w", k, err)
		}
		cur = x.callExpr(recvExpr.code+"."+t.Op, mt, targs)
	}
	if s.Mirror != "" {
		fmt.Fprintf(&b, "\t%s := %s // mirrored in %s\n", v, cur.code, s.Mirror)
	} else {
		fmt.Fprintf(&b, "\t%s := %s\n", v, cur.code)
	}
	x.declared[i] = true
	return b.String(), nil
}

func (x *exporter) typeOf(i int) reflect.Type { return x.res.Steps[i].value.Type() }

func (x *exporter) useVar(i int) string {
	x.used[x.vars[i]] = true
	return x.vars[i]
}

// sigParams returns a method's parameter names with a placeholder for its
// receiver, matching a reflect method type's parameters.
func (x *exporter) sigParams(recv reflect.Type, name string) []string {
	if recv == gridType {
		if _, ok := reflect.PointerTo(gridType.Elem()).MethodByName(name); !ok {
			recv = solidType
		}
	}
	s, ok := genSigs[typeKey(recv)+"."+name]
	if !ok {
		return nil
	}
	return append([]string{"recv"}, s.params...)
}

// methodOf finds a method on an expression's type: its type (receiver
// first) and the receiver expression, which for a grid falls back to its
// solid as the evaluator does.
func methodOf(recv expr, name string) (reflect.Type, expr, bool) {
	t := recv.t
	if m, ok := t.MethodByName(name); ok {
		return m.Type, recv, true
	}
	if t.Kind() != reflect.Pointer {
		if m, ok := reflect.PointerTo(t).MethodByName(name); ok {
			return m.Type, recv, true
		}
	}
	if t == gridType {
		return methodOf(expr{recv.code + ".Solid()", solidType}, name)
	}
	return nil, recv, false
}

func (x *exporter) funcName(c *callable) (string, error) {
	if c.reg != nil {
		p, id, ok := c.reg.importOf()
		if !ok {
			return "", fmt.Errorf("registered function %s is a closure or lives in package main; register a named function from a package to export it", c.key)
		}
		return x.pkg(p) + "." + id, nil
	}
	pkg, name, _ := strings.Cut(c.key, ".")
	return x.pkg(pkg) + "." + name, nil
}

// callExpr writes a call; a function that also returns an error is
// wrapped in must.
func (x *exporter) callExpr(fn string, t reflect.Type, args []expr) expr {
	var parts []string
	for _, a := range args {
		parts = append(parts, a.code)
	}
	code := fn + "(" + strings.Join(parts, ", ") + ")"
	if t.NumOut() == 2 {
		x.helpers["must"] = true
		code = "must(" + code + ")"
	}
	return expr{code, t.Out(0)}
}

// args converts a step's args to expressions, in parameter order from
// start, as the evaluator's call does.
func (x *exporter) args(params []string, t reflect.Type, start int, raw any) ([]expr, error) {
	n := t.NumIn()
	nonVar := n
	if t.IsVariadic() {
		nonVar = n - 1
	}
	var out []expr
	add := func(e expr) {
		out = append(out, e)
		if x.input == nil && (e.t == solidType || e.t == gridType) {
			c := e
			x.input = &c
		}
	}
	switch a := raw.(type) {
	case nil, map[string]any:
		m, _ := a.(map[string]any)
		if params == nil && len(m) > 0 {
			return nil, fmt.Errorf("args by name, but the parameter names are not known")
		}
		if n-start == 1 && !t.IsVariadic() && isParamStruct(t.In(start)) {
			if _, named := lookupArg(m, params[start]); !named {
				e, err := x.value(m, t.In(start))
				if err != nil {
					return nil, err
				}
				add(e)
				return out, nil
			}
		}
		for k := start; k < n; k++ {
			key, ok := lookupArg(m, params[k])
			if k >= nonVar {
				if !ok {
					continue
				}
				list, isList := m[key].([]any)
				if !isList {
					list = []any{m[key]}
				}
				for _, v := range list {
					e, err := x.value(v, t.In(k).Elem())
					if err != nil {
						return nil, err
					}
					add(e)
				}
				continue
			}
			if !ok {
				return nil, fmt.Errorf("missing %s", params[k])
			}
			e, err := x.value(m[key], t.In(k))
			if err != nil {
				return nil, err
			}
			add(e)
		}
	case []any:
		for j, v := range a {
			k := start + j
			pt := t.In(min(k, n-1))
			if k >= nonVar {
				pt = t.In(n - 1).Elem()
			}
			e, err := x.value(v, pt)
			if err != nil {
				return nil, err
			}
			add(e)
		}
	}
	return out, nil
}

// value is the expression for a value from the file, of type t.
func (x *exporter) value(raw any, t reflect.Type) (expr, error) {
	switch r := raw.(type) {
	case string:
		if strings.HasPrefix(r, "$") {
			p, ok := x.params[r[1:]]
			if !ok {
				return expr{}, fmt.Errorf("no param %s", r[1:])
			}
			return x.fit(p, t)
		}
		if t.Kind() == reflect.String {
			return expr{strconv.Quote(r), t}, nil
		}
		e, err := x.ref(r)
		if err != nil {
			return expr{}, err
		}
		return x.fit(e, t)
	case map[string]any:
		if op, ok := r["op"].(string); ok && (t.Kind() != reflect.Struct || !hasField(t, "op")) {
			c, ok := lookupFunc(op)
			if !ok {
				return expr{}, fmt.Errorf("no op %s", op)
			}
			name, err := x.funcName(c)
			if err != nil {
				return expr{}, err
			}
			saved := x.input
			args, err := x.args(c.params, c.fn.Type(), 0, r["args"])
			x.input = saved
			if err != nil {
				return expr{}, fmt.Errorf("%s: %w", op, err)
			}
			return x.fit(x.callExpr(name, c.fn.Type(), args), t)
		}
		if a, ok := r["anchor"]; ok && len(r) == 1 {
			def, err := decodeAnchor(a)
			if err != nil {
				return expr{}, err
			}
			e, err := x.anchor(def, x.input)
			if err != nil {
				return expr{}, err
			}
			return x.fit(e, t)
		}
		if t.Kind() == reflect.Pointer && t.Elem().Kind() == reflect.Struct {
			e, err := x.value(r, t.Elem())
			if err != nil {
				return e, err
			}
			return expr{"&" + e.code, t}, nil
		}
		if t.Kind() == reflect.Struct {
			var keys []string
			for k := range r {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			var fields []string
			for _, k := range keys {
				f, ok := fieldFor(t, k)
				if !ok {
					return expr{}, fmt.Errorf("a %s has no field %s", typeName(t), k)
				}
				e, err := x.value(r[k], f.Type)
				if err != nil {
					return expr{}, err
				}
				fields = append(fields, f.Name+": "+e.code)
			}
			return expr{x.typeExpr(t) + "{" + strings.Join(fields, ", ") + "}", t}, nil
		}
		return expr{}, fmt.Errorf("want a %s, got a map", typeName(t))
	case []any:
		if t == vec3Type || t == vec2Type {
			var parts []string
			for _, c := range r {
				e, err := x.value(c, floatType)
				if err != nil {
					return expr{}, err
				}
				parts = append(parts, e.code)
			}
			if t == vec3Type {
				return expr{x.pkg("v3") + ".XYZ(" + strings.Join(parts, ", ") + ")", t}, nil
			}
			return expr{x.pkg("v2") + ".XY(" + strings.Join(parts, ", ") + ")", t}, nil
		}
		if t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
			var parts []string
			for _, c := range r {
				e, err := x.value(c, t.Elem())
				if err != nil {
					return expr{}, err
				}
				parts = append(parts, e.code)
			}
			return expr{x.typeExpr(t) + "{" + strings.Join(parts, ", ") + "}", t}, nil
		}
		return expr{}, fmt.Errorf("want a %s, got a list", typeName(t))
	case bool:
		return expr{strconv.FormatBool(r), t}, nil
	}
	f, ok := toFloat(raw)
	if !ok {
		return expr{}, fmt.Errorf("cannot use %v", raw)
	}
	return expr{num(f), t}, nil
}

// ref is the expression for a reference: a step's variable and members.
func (x *exporter) ref(r string) (expr, error) {
	parts := strings.Split(r, ".")
	j, ok := x.names[parts[0]]
	if !ok || j >= x.i {
		return expr{}, fmt.Errorf("no earlier step %s", parts[0])
	}
	e := expr{x.useVar(j), x.typeOf(j)}
	for _, m := range parts[1:] {
		if mt, recv, ok := methodOf(e, m); ok && mt.NumIn() == 1 && mt.NumOut() == 1 {
			e = expr{recv.code + "." + m + "()", mt.Out(0)}
			continue
		}
		st := e.t
		for st.Kind() == reflect.Pointer {
			st = st.Elem()
		}
		f, ok := st.FieldByName(m)
		if !ok {
			return expr{}, fmt.Errorf("%s: no %s", r, m)
		}
		e = expr{e.code + "." + m, f.Type}
	}
	return e, nil
}

// fit converts an expression to type t, as the evaluator's assign does.
func (x *exporter) fit(e expr, t reflect.Type) (expr, error) {
	switch {
	case e.t == untypedNum:
		return expr{e.code, t}, nil
	case e.t.AssignableTo(t):
		return e, nil
	case t == vec3Type && e.t == anchoredT:
		return expr{e.code + ".Point", t}, nil
	case t == vec3Type && e.t == pointType:
		return expr{e.code + ".Pos", t}, nil
	case e.t == gridType && (t == solidType || t == sdf3Type):
		return expr{e.code + ".Solid()", solidType}, nil
	case e.t == anchoredT && t == solidType:
		return expr{e.code + ".Solid", t}, nil
	case e.t.Kind() >= reflect.Int && e.t.Kind() <= reflect.Float64 && t == floatType:
		return expr{"float64(" + e.code + ")", t}, nil
	case e.t.Kind() == reflect.Func && t.Kind() == reflect.Func && e.t.ConvertibleTo(t):
		return expr{x.typeExpr(t) + "(" + e.code + ")", t}, nil
	}
	return expr{}, fmt.Errorf("a %s where a %s is wanted", typeName(e.t), typeName(t))
}

// anchor is the expression finding an anchor: a call into package anchor.
func (x *exporter) anchor(d *AnchorDef, surf *expr) (expr, error) {
	if d.On != "" {
		e, err := x.ref(d.On)
		if err != nil {
			return expr{}, err
		}
		surf = &e
	}
	if surf == nil {
		return expr{}, fmt.Errorf("anchor with no surface")
	}
	s, err := x.fit(*surf, solidType)
	if err != nil {
		return expr{}, err
	}
	a := x.pkg("anchor")
	var code string
	switch {
	case d.Ray != nil:
		from, err := x.value(d.Ray.From, vec3Type)
		if err != nil {
			return expr{}, err
		}
		if d.Ray.Dir != nil {
			dir, err := x.value(d.Ray.Dir, vec3Type)
			if err != nil {
				return expr{}, err
			}
			code = fmt.Sprintf("%s.Ray(%s, %s, %s)", a, s.code, from.code, dir.code)
		} else {
			to, err := x.value(d.Ray.Toward, vec3Type)
			if err != nil {
				return expr{}, err
			}
			code = fmt.Sprintf("%s.Toward(%s, %s, %s)", a, s.code, from.code, to.code)
		}
	default:
		near, err := x.value(d.Nearest, vec3Type)
		if err != nil {
			return expr{}, err
		}
		code = fmt.Sprintf("%s.Nearest(%s, %s)", a, s.code, near.code)
	}
	if d.Offset != nil {
		off, err := x.value(d.Offset, floatType)
		if err != nil {
			return expr{}, err
		}
		x.helpers["offset"] = true
		code = fmt.Sprintf("offset(%s, %s)", code, off.code)
	}
	return expr{code, pointType}, nil
}

// typeExpr is the Go spelling of a type, importing its package.
func (x *exporter) typeExpr(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return "*" + x.typeExpr(t.Elem())
	case reflect.Slice:
		return "[]" + x.typeExpr(t.Elem())
	case reflect.Array:
		return fmt.Sprintf("[%d]%s", t.Len(), x.typeExpr(t.Elem()))
	}
	if t.PkgPath() == "" {
		return t.String()
	}
	return x.pkg(t.PkgPath()) + "." + t.Name()
}

func (x *exporter) helperSrc(name string) string {
	v3a := x.pkg("v3")
	switch name {
	case "must":
		return "\nfunc must[T any](v T, err error) T {\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn v\n}\n"
	case "offset":
		a := x.pkg("anchor")
		return fmt.Sprintf("\n// offset moves an anchor d along its normal, as an anchor's offset does in\n// the history.\nfunc offset(p %s.Point, d float64) %s.Point {\n\tp.Pos = p.Offset(d)\n\treturn p\n}\n", a, a)
	}
	if strings.HasPrefix(name, "mirror") {
		axis := name[6:7]
		if strings.HasSuffix(name, "s") {
			return fmt.Sprintf("\nfunc %s(vs []%s.Vec) []%s.Vec {\n\tout := make([]%s.Vec, len(vs))\n\tfor i, v := range vs {\n\t\tout[i] = mirror%s(v)\n\t}\n\treturn out\n}\n", name, v3a, v3a, v3a, axis)
		}
		return fmt.Sprintf("\n// %s reflects a vector across the plane normal to %s, as a step's\n// mirror does.\nfunc %s(v %s.Vec) %s.Vec {\n\tv.%s = -v.%s\n\treturn v\n}\n", name, strings.ToLower(axis), name, v3a, v3a, axis, axis)
	}
	return ""
}

// num writes a number so it reads back exactly: integers without a point.
func num(f float64) string {
	if f == float64(int64(f)) && f < 1e15 && f > -1e15 {
		return strconv.FormatInt(int64(f), 10)
	}
	return strconv.FormatFloat(f, 'g', -1, 64)
}
