// Package opsgen writes history/ops_gen.go: the table of every library
// function a history step can call, with its parameter names and the
// synopsis of its doc comment.
//
// Reflection finds methods and types on its own, but it cannot see
// parameter names or doc comments, and a package-level function has to be
// referenced by name to be called at all. So the source is parsed once,
// here, and the table is checked in. TestOpsTableFresh in package history
// regenerates it in memory and fails when it differs, which is how a new
// constructor that was not added to the table fails the build.
package opsgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/doc"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Packages are the library packages whose exported functions and methods
// become ops, by import name and directory under the module root.
var Packages = []struct{ Name, Dir string }{
	{"solid", "solid"},
	{"shape", "shape"},
	{"sculpt", "sculpt"},
	{"anchor", "anchor"},
	{"obj", "obj"},
	{"layout", "layout"},
	{"plane", "plane"},
}

const module = "github.com/snowbldr/fluent-sdfx"

// skip lists ops left out on purpose: they write files or report to the
// terminal, which a history step must never do. Rules in keep() catch the
// rest (a `path string` parameter, a channel, no result).
var skip = map[string]string{
	"solid.Solid.Benchmark": "prints to stdout",
	"solid.SetMinCells":     "global state",
	"solid.Solid.Voxel":     "progress channel",
}

type op struct {
	key, pkg, recv, name string
	params               []string
	doc                  string
}

// Generate returns the formatted source of ops_gen.go for the module at root.
func Generate(root string) ([]byte, error) {
	var ops []op
	for _, p := range Packages {
		found, err := scan(filepath.Join(root, p.Dir), p.Name)
		if err != nil {
			return nil, err
		}
		ops = append(ops, found...)
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].key < ops[j].key })

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./history/internal/opsgen/cmd; DO NOT EDIT.\n\n")
	b.WriteString("package history\n\nimport (\n\t\"reflect\"\n\n")
	for _, p := range Packages {
		fmt.Fprintf(&b, "\t%q\n", module+"/"+p.Dir)
	}
	b.WriteString(")\n\n")
	b.WriteString("// genFuncs is every package-level function a step can name in op.\n")
	b.WriteString("var genFuncs = map[string]any{\n")
	for _, o := range ops {
		if o.recv == "" {
			fmt.Fprintf(&b, "\t%q: %s.%s,\n", o.key, o.pkg, o.name)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// genTypes is every type with methods a step can call, keyed pkg.Type,\n")
	b.WriteString("// as a pointer so the method set covers value and pointer receivers.\n")
	b.WriteString("var genTypes = map[string]reflect.Type{\n")
	seen := map[string]bool{}
	for _, o := range ops {
		if o.recv != "" && !seen[o.pkg+"."+o.recv] {
			seen[o.pkg+"."+o.recv] = true
			fmt.Fprintf(&b, "\t%q: reflect.TypeOf((*%s.%s)(nil)),\n", o.pkg+"."+o.recv, o.pkg, o.recv)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// genSigs is the parameter names and doc synopsis of every function\n")
	b.WriteString("// and method, keyed pkg.Func or pkg.Type.Method.\n")
	b.WriteString("var genSigs = map[string]sig{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\t%q: {params: %#v, doc: %q},\n", o.key, o.params, o.doc)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("opsgen: formatting: %w", err)
	}
	return bytes.ReplaceAll(src, []byte("[]string(nil)"), []byte("nil")), nil
}

func scan(dir, pkg string) ([]op, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var ops []op
	for _, p := range pkgs {
		for _, f := range p.Files {
			for _, d := range f.Decls {
				fd, ok := d.(*ast.FuncDecl)
				if !ok || !fd.Name.IsExported() || fd.Type.TypeParams != nil {
					continue
				}
				o := op{pkg: pkg, name: fd.Name.Name}
				if fd.Recv != nil {
					o.recv = recvName(fd.Recv.List[0].Type)
					if o.recv == "" || !ast.IsExported(o.recv) {
						continue
					}
					o.key = pkg + "." + o.recv + "." + o.name
				} else {
					o.key = pkg + "." + o.name
				}
				if _, bad := skip[o.key]; bad || !keep(fd) {
					continue
				}
				n := 0
				for _, field := range fd.Type.Params.List {
					if len(field.Names) == 0 {
						o.params = append(o.params, fmt.Sprintf("arg%d", n))
						n++
					}
					for _, nm := range field.Names {
						o.params = append(o.params, nm.Name)
						n++
					}
				}
				// The table never carries an em dash, whatever the source does.
				o.doc = strings.ReplaceAll((&doc.Package{}).Synopsis(fd.Doc.Text()), " \u2014 ", ": ")
				o.doc = strings.ReplaceAll(o.doc, "\u2014", ", ")
				ops = append(ops, o)
			}
		}
	}
	return ops, nil
}

// keep says whether a function can be a step: it returns a value (or a
// value and an error), and it takes nothing a history cannot supply or
// must not touch (a file path, a channel, a function literal).
func keep(fd *ast.FuncDecl) bool {
	res := fd.Type.Results
	if res == nil || res.NumFields() == 0 || res.NumFields() > 2 {
		return false
	}
	if res.NumFields() == 2 {
		last := res.List[len(res.List)-1]
		if id, ok := last.Type.(*ast.Ident); !ok || id.Name != "error" {
			return false
		}
	}
	for _, field := range fd.Type.Params.List {
		switch field.Type.(type) {
		case *ast.ChanType, *ast.FuncType:
			return false
		}
		for _, nm := range field.Names {
			if id, ok := field.Type.(*ast.Ident); ok && id.Name == "string" && (nm.Name == "path" || nm.Name == "filename") {
				return false
			}
		}
	}
	return true
}

func recvName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return recvName(t.X)
	case *ast.Ident:
		return t.Name
	case *ast.IndexExpr:
		return "" // generic receiver
	}
	return ""
}
