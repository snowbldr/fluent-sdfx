package score

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"
)

// Module is the Go module path of this repository.
const Module = "github.com/snowbldr/fluent-sdfx"

// scorerMain is the generated program that imports a task's reference
// package and a candidate package (both must export Build() *solid.Solid),
// scores them, and prints the Result as JSON on stdout.
var scorerMain = template.Must(template.New("main").Parse(`// Code generated by bench/score; DO NOT EDIT.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"{{.Module}}/bench/score"
	"{{.Module}}/solid"
	ref "{{.RefPkg}}"
	cand "{{.CandPkg}}"
)

func main() {
	spec, err := score.LoadSpec({{printf "%q" .SpecPath}})
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	r := score.Result{Task: spec.Name, Compiled: true}
	refS, err := score.Guard(func() *solid.Solid { return ref.Build() })
	if err != nil {
		r.Error = "reference: " + err.Error()
		emit(r)
		os.Exit(3)
	}
	candS, err := score.Guard(func() *solid.Solid { return cand.Build() })
	if err != nil {
		r.Error = err.Error()
		emit(r)
		return
	}
	r = score.Compare(refS, candS, spec)
	emit(r)
}

func emit(r score.Result) {
	b, _ := json.MarshalIndent(r, "", "  ")
	os.Stdout.Write(b)
	os.Stdout.Write([]byte("\n"))
}
`))

// Score compiles and runs a generated scorer for taskDir against the
// candidate package at candDir. Both directories must live inside this
// module. A compile failure of the candidate is reported as a Result with
// Compiled=false rather than an error; other failures return err.
func Score(repoRoot, taskDir, candDir, workDir string) (Result, error) {
	taskAbs, _ := filepath.Abs(taskDir)
	candAbs, _ := filepath.Abs(candDir)
	rootAbs, _ := filepath.Abs(repoRoot)
	refPkg, err := pkgPath(rootAbs, filepath.Join(taskAbs, "reference"))
	if err != nil {
		return Result{}, err
	}
	candPkg, err := pkgPath(rootAbs, candAbs)
	if err != nil {
		return Result{}, err
	}
	spec, err := LoadSpec(taskAbs)
	if err != nil {
		return Result{}, err
	}

	workDir, _ = filepath.Abs(workDir)
	if err := os.MkdirAll(workDir, 0o755); err != nil {
		return Result{}, err
	}
	mainPath := filepath.Join(workDir, "main.go")
	var buf bytes.Buffer
	if err := scorerMain.Execute(&buf, map[string]string{
		"Module": Module, "RefPkg": refPkg, "CandPkg": candPkg,
		"SpecPath": filepath.Join(taskAbs, "task.json"),
	}); err != nil {
		return Result{}, err
	}
	if err := os.WriteFile(mainPath, buf.Bytes(), 0o644); err != nil {
		return Result{}, err
	}

	// Stage 0: does the candidate compile on its own?
	build := exec.Command("go", "vet", "./"+rel(rootAbs, candAbs))
	build.Dir = rootAbs
	if out, err := build.CombinedOutput(); err != nil {
		return Result{Task: spec.Name, Compiled: false, Error: strings.TrimSpace(string(out))}, nil
	}

	run := exec.Command("go", "run", "./"+rel(rootAbs, workDir))
	run.Dir = rootAbs
	var stdout, stderr bytes.Buffer
	run.Stdout, run.Stderr = &stdout, &stderr
	runErr := run.Run()
	var r Result
	if stdout.Len() > 0 {
		if jerr := json.Unmarshal(stdout.Bytes(), &r); jerr != nil {
			return Result{}, fmt.Errorf("bad scorer output: %v\n%s\n%s", jerr, stdout.String(), stderr.String())
		}
		if r.Error == "" && runErr != nil {
			r.Error = strings.TrimSpace(stderr.String())
		}
		return r, nil
	}
	if runErr != nil {
		return Result{Task: spec.Name, Compiled: false, Error: strings.TrimSpace(stderr.String())}, nil
	}
	return Result{}, fmt.Errorf("scorer produced no output")
}

func pkgPath(root, dir string) (string, error) {
	r, err := filepath.Rel(root, dir)
	if err != nil || strings.HasPrefix(r, "..") {
		return "", fmt.Errorf("%s is not inside module root %s", dir, root)
	}
	return Module + "/" + filepath.ToSlash(r), nil
}

func rel(root, dir string) string {
	r, _ := filepath.Rel(root, dir)
	return filepath.ToSlash(r)
}
